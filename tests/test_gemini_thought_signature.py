"""Gemini 3 thought-signature bypass for foreign tool history
(2026-11-25 census, thread b — root cause found by live probe).

google/gemini-3.1-flash-lite 400s chronically (~112 request_fault
attempts in the census week, daily since Nov 13). A pinned live probe
with a tool-history conversation returned Google's actual error:
"Function call is missing a thought_signature in functionCall parts."
Gemini 3 enforces thought-signature validation on replayed function
calls; a router that switches models mid-conversation replays tool
calls ORIGINATED BY OTHER MODELS, which carry no Google signature.

Google's own documentation names this exact case — "functionCall
parts that were not generated by the API ... for example, when
transferring history from a model that does not include thought
signatures" — and documents the bypass value
`skip_thought_signature_validator` for it (last resort; may reduce
quality vs a real signature, but the alternative is a hard 400).

The gateway therefore injects the bypass as
extra_content.google.thought_signature on assistant tool_calls that
lack a signature, ONLY when the upstream is a direct-Google Gemini 3
entry. A real signature from the client is never overwritten, the
client's body is never mutated (shaping is copy-on-write so a later
fallback attempt to another provider sees no Google metadata), and
no other provider/family is touched.
"""

from __future__ import annotations

import copy
import hashlib
import json
import sys
from pathlib import Path
from types import SimpleNamespace

import httpx
from fastapi.testclient import TestClient

SRC = Path(__file__).resolve().parent.parent / "src"
sys.path.insert(0, str(SRC))

from conftest import auth  # noqa: E402
from gateway import (  # noqa: E402
    _THOUGHT_SIGNATURE_BYPASS,
    GatewayConfig,
    _needs_thought_signature_bypass,
    _with_thought_signature_bypass,
    create_app,
)

GEMINI = "google/gemini-3.1-flash-lite"
BYPASS = "skip_thought_signature_validator"


def _entry(provider, model):
    return SimpleNamespace(provider=provider, model=model)


def _history():
    return [
        {"role": "user", "content": "What is the weather in Rapid City?"},
        {"role": "assistant", "content": None, "tool_calls": [{
            "id": "call_1", "type": "function",
            "function": {"name": "get_weather",
                         "arguments": "{\"city\": \"Rapid City\"}"}}]},
        {"role": "tool", "tool_call_id": "call_1", "content": "sunny, 40F"},
        {"role": "user", "content": "Should I wear a jacket?"},
    ]


# ----------------------------------------------------------------------
# predicate: only direct-Google Gemini 3 entries
# ----------------------------------------------------------------------

def test_predicate_scope():
    assert _needs_thought_signature_bypass(
        _entry("google", "gemini-3.1-flash-lite"))
    assert _needs_thought_signature_bypass(
        _entry("google", "gemini-3.5-flash-lite"))
    assert not _needs_thought_signature_bypass(
        _entry("google", "gemma-4-31b-it"))
    assert not _needs_thought_signature_bypass(
        _entry("google", "gemini-2.5-flash"))
    assert not _needs_thought_signature_bypass(
        _entry("openrouter", "google/gemini-3.1-flash-lite"))
    assert not _needs_thought_signature_bypass(
        _entry("groq", "openai/gpt-oss-120b"))
    assert _THOUGHT_SIGNATURE_BYPASS == BYPASS


# ----------------------------------------------------------------------
# shaping: inject where absent, preserve where present, never mutate
# ----------------------------------------------------------------------

def test_bypass_injected_on_unsigned_tool_calls():
    out = _with_thought_signature_bypass(_history())
    tc = out[1]["tool_calls"][0]
    assert tc["extra_content"]["google"]["thought_signature"] == BYPASS


def test_real_signature_preserved():
    msgs = _history()
    msgs[1]["tool_calls"][0]["extra_content"] = {
        "google": {"thought_signature": "REAL-SIGNATURE"}}
    out = _with_thought_signature_bypass(msgs)
    tc = out[1]["tool_calls"][0]
    assert tc["extra_content"]["google"]["thought_signature"] \
        == "REAL-SIGNATURE"


def test_input_not_mutated():
    msgs = _history()
    before = copy.deepcopy(msgs)
    _with_thought_signature_bypass(msgs)
    assert msgs == before


def test_no_tool_calls_no_change():
    msgs = [{"role": "user", "content": "hello"},
            {"role": "assistant", "content": "hi"}]
    out = _with_thought_signature_bypass(msgs)
    assert out == msgs


# ----------------------------------------------------------------------
# gateway integration: the shaped payload is what reaches upstream
# ----------------------------------------------------------------------

def build_google_app(tmp_path, handler):
    """Recording app whose hermes carries the PRODUCTION lane set
    (incl. public-only-free, where the google entries live) — the
    shared harness's narrower test lanes 403 a google pin, which is
    a harness premise, not production behaviour."""
    def sha(v):
        return hashlib.sha256(v.encode()).hexdigest()

    clients_file = tmp_path / "clients-google.json"
    clients_file.write_text(json.dumps({
        "admin_key_sha256": sha("admin-test-key"),
        "clients": [{
            "id": "hermes", "key_sha256": sha("hermes-test-key"),
            "lanes": ["private-free", "paid", "public-only-free"],
            "premium_allowed": False, "daily_target_usd": 1.0}]}))
    calls: list[dict] = []

    def transport_handler(request: httpx.Request) -> httpx.Response:
        body = json.loads(request.content)
        calls.append(body)
        return handler(body["model"], body, len(calls))

    cfg = GatewayConfig(
        state_dir=tmp_path / "state", clients_path=clients_file,
        registry_path=SRC / "registry.json",
        provider_keys={"google": "fake", "openrouter": "fake",
                       "groq": "fake", "deepinfra": "fake",
                       "openai": "fake", "deepseek": "fake",
                       "zai": "fake", "ollama": "fake"})
    app = create_app(
        cfg, upstream_transport=httpx.MockTransport(transport_handler))
    return app, calls


def test_gateway_sends_bypass_to_gemini_upstream(tmp_path):
    def handler(model, body, call_no):
        return httpx.Response(200, json={
            "id": "x", "object": "chat.completion", "model": model,
            "choices": [{"index": 0, "finish_reason": "stop",
                         "message": {"role": "assistant",
                                     "content": "Wear a light jacket."}}],
            "usage": {"prompt_tokens": 10, "completion_tokens": 5,
                      "total_tokens": 15}})

    app, calls = build_google_app(tmp_path, handler)
    body = {"model": GEMINI, "messages": _history(), "max_tokens": 64}
    with TestClient(app) as client:
        r = client.post("/v1/chat/completions", json=body,
                        headers=auth("hermes"))
    assert r.status_code == 200
    assert len(calls) == 1
    sent_tc = calls[0]["messages"][1]["tool_calls"][0]
    assert sent_tc["extra_content"]["google"]["thought_signature"] \
        == BYPASS
